// https://leetcode.cn/problems/sort-colors/description/

// 区间划分
// |-------|-------|-----------------|
//    红       白     未处理区又是蓝区
//         p       q
// 对于未处理区，将其中的红白都移出去后，它就是蓝区。
// [0, p) 是红区，[p, q) 是白区，[q, n) 是未处理区又是蓝区。
//
// 初始时 p 和 q 都为 0，那么
//	a. 红区是 [0, p=0)，白区是 [p=0, q=0)，都是空区间，刚好跟实际情况相符。
//  b. 红白两区混沌未分，p 同时表示如下多个概念：
// 		1. 红区右开边界
//      2. 下一个红色要存储的位置
//      3. 白区左闭边界
//      4. 下一个白色要存储的位置。这点不好理解，关键在于红白两区混沌未分，还有白区为空。
//         白区为空，意味着 p 和 q 都可表示下一个白色要存储的位置
//      5. 未处理区间的左闭边界
//
// 先分出或填充出红区。一旦红区非空，红白两区就有明确的边界了。
// 当红区不为空但白区为空时，p 可表示
// 	1. 下一个红色要存储的位置
//  2. 白区左闭边界
//  3. 下一个白色要存储的位置
//  4. 未处理区间的左闭边界
//
// 一旦白区也非空了，p 可表示
// 	1. 下一个红色要存储的位置
//  2. 白区左闭边界或叫白区第一个位置
//
// 如果遍历数组期间同时划分红、白两区，而白区又紧邻红区的右侧，当需要扩充红区时，怎么办？
// 对应 sortColors2 实现
//
// 如果先分出红区，完成后再分出白区，就
// 	a. 不会产生 红白两区边界已出现的情况下还需要扩充红区的 情形
//  b. 不需要 p、q 两个指针了，只需要一个指针 p 表示正在划分的区和待处理区之间的边界就够了
// 对应 sortColors 实现

// 算法思路：
//  1. 初始时，红白两区混沌未分。
//  2. 先分出红区，完成后再分出白区。这样就只需创建一个指针 p，初始时为 0
//  3. 红区未分时，p 表示红区右开边界，即下一个红色要存储的位置。
//     用 i 从 0 开始遍历数组。如果 nums[i] 为红色，就跟 nums[p] 交换
//     遍历结束后，红区就划分完成了。
//  4. 白区未分时，p 表示白区右开边界，即下一个白色要存储的位置，也是未处理区间的左闭边界
//     用 i 从 p 开始遍历数组。如果 nums[i] 为白色，就跟 nums[p] 交换
//     遍历结束后，白区就划分完成了。
func sortColors(nums []int) {
	if len(nums) == 0 || len(nums) == 1 {
		return
	}

	// p 是下一个红色要存储的位置
	p := 0
	for i := range nums {
		// p 是下一个红色要存储的位置，因此若是红色，就交换 nums[p] 和 nums[i]
		if nums[i] == 0 {
			nums[p], nums[i] = nums[i], nums[p]
			p++
		}
		// 不管 nums[i] 是否是红色，都要 i++ 以继续扫描
	}

	// 红区已分，但白区未分。此时 p 既是未处理区间的左闭边界，同时也是下一个白色要存储的位置
	for i := p; i < len(nums); i++ {
		// 若 i 和 p 相等，且所指元素为白色，交换它们，没有任何坏处
		// 若 i 和 p 不相等，那么 nums[p] 必然已被扫描且肯定不是白色，
		// 而 nums[i] 是白色，这正是必须交换的情形
		if nums[i] == 1 {
			nums[p], nums[i] = nums[i], nums[p]
			p++
		}
		// 不管 nums[i] 是否是白色，都要 i++ 以继续扫描
	}
}

// 算法思路：
// 1. 用 p、q 两个指针分别表示红区、白区的右开边界，或下一个红色、白色要存储的位置
// 2. 初始时红白两区混沌未分，因此，p、q 都为 0，重叠在一起
// 3. 用 i 遍历整个数组
// 		a. 若 nums[i] 为红色，交换 nums[p] 和 nums[i]。
// 		   【注意】，若 p < q，表明红白两区边界已出现了，刚才的交换就把白区第一个元素换到了 i 位置。
//         还需要再交换 nums[i] 和 nums[q]，将白区第一个元素追加到白区末尾
// 		b. 若为白色，交换 nums[q] 和 nums[i]

func sortColors2(nums []int) {
	if len(nums) == 0 || len(nums) == 1 {
		return
	}

	// p、q 分别表示下一个红色、白色要存储的位置
	p, q := 0, 0
	for i := range nums {
		if nums[i] == 0 { // 红色
			nums[p], nums[i] = nums[i], nums[p]
			// 初始时 p == q 表示红白两区混沌未分。若 p < q，表示红白两区边界已出现了，
			// 这意味着 p 既是下一个红色要存储的位置，同时又是白区的第一个位置。
			// 现在已经将 白区的第一个元素 和 刚找到的红色 交换了位置，那么白区的第一个元素
			// 现在是 nums[i]，再把它跟 nums[q] 交换下就把白区的第一个元素追加到白区尾部了。
			// 注意，q 就是下一个白色要存储的位置
			if p < q {
				nums[i], nums[q] = nums[q], nums[i]
			}

			// 追加了红色，因此必须移动 p，以指向下一个红色要存储的位置
			p++
			// 不管红白两区边界是否已出现，只要红区向右扩充了，
			// 那么紧邻红区右侧的白区的右边界也要右移
			q++
		} else if nums[i] == 1 { // 白色
			nums[q], nums[i] = nums[i], nums[q]
			q++
		}
	}
}

// 区间划分
// |--------|--------------------|-------|
//
//	  红区        白区又是未处理区     蓝区
//	        p                    q
//
// 对于未处理区，将其中的红蓝都移出去后，它就是白区。
// [0, p) 是红区，[p, q] 是白区和未处理区，(q, n-1] 是蓝区
//
// 算法思路：
//  1. 用 p、q 分别表示红区 [0, p) 右开边界、蓝区 (q, n-1] 左开边界，或者下一个红色、蓝色要存储的位置。
//     更重要的是，p 向右扩充，q 向左扩充
//  2. 初始时，p、q 分别为 0、n-1，这样红区、蓝区都是空区间，跟实际情况也相符
//  3. 用 i 从 p 开始遍历数组，循环条件是 i<=q
//     a. 若 nums[i] 为红色 0，跟 nums[p] 交换
//     b. 若 nums[i] 为蓝色 2，
//     nums[i] 与 nums[q] 交换之后，nums[i] 可能还是蓝色 2，因此，
//     这里需要循环交换 nums[i] 与 nums[q]，每次迭代左移 q。
//     循环条件为 i<=q && nums[i]==2，直到 nums[i]!=2
//     c. 若 nums[i] 为白色 1，不需要做什么
//
// 为什么 nums[i] 为红色时，不需要做为蓝色时那样的循环交换呢？
// 因为 i 是从 p 开始扫描的，nums[p] 已被检测过，一次交换后所放位置就是正确的。
// 而 nums[q] 未被检测过，不知道它是哪种颜色，nums[i] 跟它交换后，i 位置的颜色可能是不正确的

func sortColors3(nums []int) {
	if len(nums) == 0 || len(nums) == 1 {
		return
	}

	p, q := 0, len(nums)-1
	// i 必须走到 q，因为 nums[q] 可能是红色，需要跟 nums[p] 交换
	for i := 0; i <= q; i++ {
		// 如果是蓝色
		for ; i <= q && nums[i] == 2; q-- {
			nums[q], nums[i] = nums[i], nums[q]
		}
		// 如果是红色
		if nums[i] == 0 {
			nums[p], nums[i] = nums[i], nums[p]
			p++
		}
		// 如果是白色，什么都不做
	}
}

func TestSortColor(t *testing.T) {
	nums := []int{2, 0, 2, 1, 1, 0}
	func() {
		sortColors3(nums)
		fmt.Printf("nums:%v\n", nums)
	}()
}
