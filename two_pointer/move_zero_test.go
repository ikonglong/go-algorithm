package twopointer

// https://leetcode.cn/problems/move-zeroes/

// 如果不要求保留非零元素的相对顺序，实现算法就比较简单，类似在数组上分出奇数和偶数区。
//
// 但题目要求保留非零元素的相对顺序，怎样才能做到呢？
//
// 区间划分 1
// |-------|-------|-----------------|
//   非0区     0区        未处理区
//         p       q
//
// 区间划分 2
// |-------|-------------------------|
//   非0区     未处理区也是0区
//         p
//
// 不管采用哪种区间划分方式，只要将未处理区中的非0元素按顺序逐个追加至非0区，就能做到保留
// 非零元素的相对顺序。看图可知，采用第二种区间划分方式更简单一些
//
//
// 采用区间划分 1 的实现：moveZeroes
// 采用区间划分 2 的实现：moveZeroes2
//

// 算法思路：
// 1. 采用前述第 1 种区间划分方式
// 		a. 用 p 表示非零区右开边界或下一个非零元素的存储位置，也是零区的第一个位置
// 		b. 用 q 表示零区右开边界或下一个 0 的存储位置，也是未处理区的开始
// 2. 初始时，非零区、零区混沌未分，可以认为它们的右边界重叠在一起，因此 p、q 都为 0
// 3. 用 q 遍历数组，这样就可以慢慢分出非零区和零区
// 		a. 若 nums[q] 是 0，右移 q 就将当前元素添加至邻区末尾了
//      b. 若 nums q 非零，则交换 nums[p] 和 nums[q]。
//         因为非零区向右扩充了，所以 p 和 q 都要右移。
//         如果交换前 nums[p] 是 0，交换后的效果刚好是把当前非零元素放入 0 区第一个位置，
//         把 0 区第一个元素追加到了 0 区末尾，而 0 区第一个位置就是当前非零元素要存储的位置

func moveZeroes(nums []int) {
	p, q := 0, 0
	for q < len(nums) {
		if nums[q] == 0 {
			q++ // 添加至0区末尾
		} else {
			// 交换 0 区左边界和nums[q]，再
			// 右移非 0 区右开边界，以计入新增非 0 元素
			// 右移 0 区右开边界，以计入换过来的 0 元素
			nums[p], nums[q] = nums[q], nums[p]
			p++
			q++
		}
	}
}

// 采用前述第 2 种区间划分方式
func moveZeroes2(nums []int) {
	// p 表示非零区右开边界，即下一个非零元素要存储的位置
	p := 0
	// 用 i 扫描找非零元素，找到，交换，继续找下一个
	for i:=p; i<len(nums); i++ {
		if nums[i] != 0 {
			nums[p], nums[i] = nums[i], nums[p]
			p++
		}
	}
}
